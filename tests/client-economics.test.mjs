import assert from 'node:assert/strict';
import {clientPriceChain,negotiatePrice,negotiationInputPrice} from '../src/client-economics.js';
const close=(a,b)=>assert.ok(Math.abs(a-b)<1e-8,`${a} / ${b}`);
const source={volumeKg:100,priceRubKg:200,reportedCostRubKg:130,reportedLogisticsRub:500,marginRub:6000,reconciliationRub:500};
const chain=clientPriceChain(source);
close(chain.bars.slice(0,-1).reduce((sum,bar)=>sum+bar.value,0),chain.margin);
assert.equal(chain.reconciliation,5);
assert.equal(clientPriceChain({...source,reportedLogisticsRub:null}).bars,null);
assert.equal(clientPriceChain({...source,volumeKg:0}).bars,null);
assert.equal(clientPriceChain({...source,reportedCostRubKg:Infinity}).bars,null);
const negative=clientPriceChain({...source,reportedCostRubKg:220,marginRub:-2500,reconciliationRub:0});
assert.equal(negative.margin,-25);
close(negative.bars.slice(0,-1).reduce((sum,bar)=>sum+bar.value,0),-25);
const terms={basePrice:200,volumeKg:100,price:210,cost:130,logistics:10,deductions:0,targetMargin:30};
let result=negotiatePrice(terms);
assert.equal(result.revenueChangeRub,1000);
close(result.thresholdPriceRubKg,200);
close(result.discountHeadroomPct,100/21);
result=negotiatePrice({...terms,price:190});
assert.equal(result.revenueChangeRub,-1000);
assert.ok(result.discountHeadroomPct<0);
for(const missing of ['cost','logistics','deductions','targetMargin']){
 const r=negotiatePrice({...terms,[missing]:null});
 assert.equal(r.thresholdPriceRubKg,null);assert.equal(r.discountHeadroomPct,null);
 assert.equal(r.revenueChangeRub,1000);
}
for(const invalid of [99.99,100,101,-1,Infinity,NaN])assert.equal(negotiatePrice({...terms,targetMargin:invalid}).thresholdPriceRubKg,null);
result=negotiatePrice({...terms,deductions:12});
close(result.thresholdPriceRubKg,212);
close(result.discountHeadroomPct,-20/21);
close((result.thresholdPriceRubKg-12-130-10)/(result.thresholdPriceRubKg-12),.3);
assert.equal(result.revenueChangeRub,1000);
result=negotiatePrice({...terms,cost:0,logistics:0,targetMargin:0});
assert.equal(result.thresholdPriceRubKg,0);assert.equal(result.discountHeadroomPct,100);
result=negotiatePrice({...terms,price:0});
assert.equal(result.revenueChangeRub,-20000);assert.equal(result.discountHeadroomPct,null);
assert.equal(negotiatePrice({...terms,volumeKg:null}).revenueChangeRub,null);
assert.equal(negotiatePrice({...terms,price:'210'}).revenueChangeRub,null);
assert.equal(negotiatePrice({...terms,price:1e308,volumeKg:1e308}).revenueChangeRub,null);
assert.equal(negotiatePrice({...terms,cost:1e308,logistics:1e308}).thresholdPriceRubKg,null);
for(const key of ['cost','logistics','deductions'])for(const invalid of [1e6+1,-1,Infinity,NaN,'0'])assert.equal(negotiatePrice({...terms,[key]:invalid}).thresholdPriceRubKg,null);
for(const key of ['price','basePrice'])for(const invalid of [1e6+1,-1,Infinity,NaN,'0'])assert.equal(negotiatePrice({...terms,[key]:invalid}).revenueChangeRub,null);
assert.equal(negotiatePrice({...terms,volumeKg:1e12+1}).revenueChangeRub,null);
result=negotiatePrice({basePrice:0,volumeKg:1e12,price:1e6,cost:1e6,logistics:1e6,deductions:1e6,targetMargin:99.9});
assert.ok(Object.values(result).every(Number.isFinite));
assert.equal(result.revenueChangeRub,1e18);
assert.equal(negotiatePrice({...terms,price:Number.MIN_VALUE}).discountHeadroomPct,null);
assert.equal(source.marginRub,6000);
const historicalPrice=159.2221490755123,historicalVolume=12635870;
const historicalTerms={...terms,basePrice:historicalPrice,volumeKg:historicalVolume};
assert.equal(negotiatePrice({...historicalTerms,price:negotiationInputPrice(null,historicalPrice)}).revenueChangeRub,0);
assert.equal(negotiationInputPrice('',historicalPrice),null);
assert.equal(negotiatePrice({...historicalTerms,price:negotiationInputPrice('',historicalPrice)}).revenueChangeRub,null);
assert.equal(negotiationInputPrice('159.22',historicalPrice),159.22);
close(negotiatePrice({...historicalTerms,price:negotiationInputPrice('160',historicalPrice)}).revenueChangeRub,(160-historicalPrice)*historicalVolume);
console.log('Проверены цепочка отчёта, расхождение, удержания, неизвестные затраты, порог, скидка, конечность расчёта и точный нулевой эффект начальной цены');
